// Примеры под ситуацию: главная эмоция + вторая, если есть
function supShots(d,sex){
  const ids=(d&&d.intents||[]).filter(id=>SUP_EXAMPLES[id]);
  let pairs=[];
  if(ids.length>=2)pairs=[SUP_EXAMPLES[ids[0]][0],SUP_EXAMPLES[ids[1]][0]];
  else pairs=(SUP_EXAMPLES[ids[0]]||SUP_EXAMPLES.default).slice(0,2);
  const out=[];pairs.forEach(([u,a])=>{out.push({role:'user',content:u});out.push({role:'assistant',content:supG(a,sex)});});
  return out;
}

// ── распознавание ───────────────────────────────────────────

// Род обращения: «написал{|а}» → «написал» / «написала» по полу из профиля Tempo
function supG(t,sex){return String(t).replace(/\{([^|{}]*)\|([^{}]*)\}/g,(m,a,b)=>sex==='f'?b:a);}

function supNorm(t){return String(t||'').toLowerCase().replace(/ё/g,'е').replace(/\s+/g,' ').trim();}

function supDetect(text){
  const t=supNorm(text),raw=String(text||'').toLowerCase();
  const joking=/от смеха|со смеху|смешно|ахах|хаха|лол/.test(t);
  const crisis=SUP_CRISIS_RE.some(r=>r.test(raw)||r.test(t))&&!(joking&&!/не хочу жить|самоуби|суицид|покончить|убить себя|режу себя/.test(t));
  const intents=SUP_INTENTS.filter(x=>x.re.test(raw)||x.re.test(t));
  // радость не считаем, если рядом явный негатив («не получилось»)
  const neg=/не получилось|не смог|не сдал|не сделал|не рад/.test(t);
  const list=intents.filter(x=>!(x.id==='joy'&&(neg||intents.length>1&&intents.some(y=>['sad','anxiety','tired','anger','lonely'].includes(y.id)))));
  const tools=[];list.forEach(x=>x.tools.forEach(k=>{if(!tools.includes(k))tools.push(k);}));
  return{crisis,intents:list.map(x=>x.id),primary:list[0]||null,hints:list.slice(0,2).map(x=>x.hint),tools:tools.slice(0,2)};
}

// ── контекст из Tempo ───────────────────────────────────────
// ctx: {name, hour, mood(1–5), sleep, readiness, readinessMode, streak, workoutToday, habitsDone, habitsTotal}

function supContextLine(ctx){
  if(!ctx)return'';
  const p=[];
  if(ctx.name)p.push('Имя: '+ctx.name+'.');
  if(ctx.sex)p.push(ctx.sex==='f'?'Это девушка — обращайся в женском роде.':'Это парень — обращайся в мужском роде.');
  if(ctx.hour!=null)p.push('Сейчас '+(ctx.hour<5?'ночь':ctx.hour<12?'утро':ctx.hour<18?'день':'вечер')+'.');
  if(ctx.mood)p.push('Настроение в дневнике: '+['','очень плохое','плохое','среднее','хорошее','отличное'][ctx.mood]+'.');
  if(ctx.sleep!=null)p.push('Спал '+String(ctx.sleep).replace('.',',')+' ч.');
  if(ctx.readiness!=null)p.push('Готовность к нагрузке: '+ctx.readiness+' из 100.');
  if(ctx.workoutToday)p.push('Сегодня была тренировка.');
  if(ctx.habitsTotal)p.push('Привычки сегодня: '+ctx.habitsDone+' из '+ctx.habitsTotal+'.');
  if(ctx.streak>=3)p.push('Заходит в Tempo '+ctx.streak+' дней подряд.');
  if(ctx.week)p.push('За неделю: '+ctx.week+'.');
  return p.join(' ');
}

// ── сборка запроса ──────────────────────────────────────────
// history: [{r:'u'|'a', t}] — прошлые сообщения (без текущего)

function supBuildMessages(o){
  let sys=SUP_SYSTEM;
  const cl=o.ctxOn===false?'':supContextLine(o.ctx);
  if(cl)sys+='\nО человеке (используй мягко и только если к месту): '+cl;
  const d=o.detect||supDetect(o.text);
  const msgs=[{role:'system',content:sys},...supShots(d,o.ctx&&o.ctx.sex)];
  const hist=(o.history||[]).filter(m=>m.t&&!m.x).slice(-6);
  hist.forEach(m=>msgs.push({role:m.r==='u'?'user':'assistant',content:m.t.length>400?m.t.slice(0,400)+'…':m.t}));
  let u=String(o.text||'').trim();
  const mode=o.hintMode||SUP_HINT_MODE;
  if(d.hints.length&&mode==='user')u+='\n\n(Как лучше ответить: '+d.hints.join(' ')+')';
  if(d.hints.length&&mode==='system')msgs[0].content+='\nСейчас: '+d.hints.join(' ');
  msgs.push({role:'user',content:u});
  return msgs;
}

// ── чистка ответа ───────────────────────────────────────────

function supClean(text){
  let t=String(text||'');
  t=t.replace(/<think>[\s\S]*?<\/think>/g,'').replace(/<\/?think>/g,'');
  t=t.replace(/\(Как лучше ответить[^)]*\)?/g,'').replace(/\[Подсказка[^\]]*\]?/g,'');
  t=t.replace(/[֐-ۿ฀-๿぀-ヿ㐀-鿿가-힯]+/g,''); // чужие алфавиты — у маленьких Qwen бывает
  t=t.replace(/(^|[\s,])([а-яё]+)(\s+\2)+(?=[\s,.!?])/gi,'$1$2');                          // «просто просто»
  t=t.replace(/\*\*|__|^#+\s*/gm,'').replace(/^\s*[-•*]\s+/gm,'').replace(/^\s*\d+[.)]\s+/gm,'');
  t=t.replace(/^(Здравствуйте|Здравствуй)[!,.]?\s*/i,'');
  t=t.replace(/[ \t]+/g,' ').replace(/\n{3,}/g,'\n\n').trim();
  // убираем повторяющиеся предложения
  const parts=t.match(/[^.!?…]+[.!?…]+["»)]?|[^.!?…]+$/g)||[t];
  const seen=new Set(),keep=[];
  parts.forEach(p=>{const k=supNorm(p).replace(/[^a-zа-я0-9 ]/g,'');if(k.length<3||!seen.has(k)){seen.add(k);keep.push(p);}});
  t=keep.join('').trim();
  t=supTy(t);
  // не больше 4 предложений; вопрос в конце сохраняем — он продолжает разговор
  const sents=t.match(/[^.!?…]+[.!?…]+["»)]?\s*/g);
  if(sents&&sents.length>4&&sents.join('').length>=t.length*0.9){
    const q=sents.slice(3).reverse().find(x=>/\?/.test(x));
    t=(sents.slice(0,3).join('')+(q||sents[3])).trim();
  }
  // обрезаем недописанное последнее предложение (упёрлись в лимит токенов)
  if(!/[.!?…)»]$/.test(t)){const cut=Math.max(t.lastIndexOf('. '),t.lastIndexOf('! '),t.lastIndexOf('? '),t.lastIndexOf('.\n'),t.lastIndexOf('?\n'));if(cut>40)t=t.slice(0,cut+1);else t+='…';}
  return t;
}

// «Вы» → «ты» там, где это можно сделать без риска; остальное ловит supIsBad → перегенерация
const SUP_VY=[[/(^|[^а-яё])у вас([^а-яё]|$)/gi,'$1у тебя$2'],[/(^|[^а-яё])вас([^а-яё]|$)/gi,'$1тебя$2'],[/(^|[^а-яё])вам([^а-яё]|$)/gi,'$1тебе$2'],[/(^|[^а-яё])вами([^а-яё]|$)/gi,'$1тобой$2'],
  [/(^|[^а-яё])ваш([^а-яё]|$)/gi,'$1твой$2'],[/(^|[^а-яё])ваша([^а-яё]|$)/gi,'$1твоя$2'],[/(^|[^а-яё])ваше([^а-яё]|$)/gi,'$1твоё$2'],[/(^|[^а-яё])ваши([^а-яё]|$)/gi,'$1твои$2'],
  [/(^|[^а-яё])вашу([^а-яё]|$)/gi,'$1твою$2'],[/(^|[^а-яё])вашего([^а-яё]|$)/gi,'$1твоего$2'],[/(^|[^а-яё])вашей([^а-яё]|$)/gi,'$1твоей$2'],[/(^|[^а-яё])ваших([^а-яё]|$)/gi,'$1твоих$2'],
  [/(^|[^а-яё])вашим([^а-яё]|$)/gi,'$1твоим$2'],[/(^|[^а-яё])вашими([^а-яё]|$)/gi,'$1твоими$2'],[/(^|[^а-яё])вашем([^а-яё]|$)/gi,'$1твоём$2']];
// Частые глаголы, у которых «-ите» — точно повелительное наклонение
const SUP_VY_ITE=/^(вы|в|по|с|на|о|от|пере|рас|раз|у|за|при|про|под|до)?(дохните|дохнитесь|пишите|звоните|говорите|скажите|просите|спросите|пустите|отпустите|найдите|возьмите|смотрите|посмотрите|ходите|выйдите|дите|ложитесь|ляжьте|вернитесь|обратитесь|отвлекитесь|отдохните|берегите|цените|хвалите|простите|помните|вспомните|сохраните|уберите|выберите|соберите|начните|остановитесь|задержите|опустите|поднимите|закройте|откройте|позвольте|учитесь|пейте|ешьте|спите|дышите|подышите|включите|выключите|отложите|положите|отключите|перечитайте)$/;
const SUP_VY_KEEP=/^(сайте|чайте|майте|найте|вите|сите|пите|ните|ките|быте)$/;
function supTy(t){
  let s=String(t);
  SUP_VY.forEach(([re,to])=>{s=s.replace(re,(m,...g)=>{const out=m.replace(re,to);return /^[А-ЯЁ]/.test(m.replace(/^[^а-яё]*/i,''))?out.replace(/[а-яё]/i,c=>c.toUpperCase()):out;});});
  // повелительное мн. ч. → ед. ч., только если нет самого «вы» (иначе это может быть «вы говорите»)
  if(!/(^|[^а-яё])вы([^а-яё]|$)/i.test(s)){
    s=s.replace(/([а-яё]{3,})(йтесь|йте|ьтесь|ьте|итесь|ите)(?=[^а-яё]|$)/gi,(m,base,end)=>{
      const e=end.toLowerCase(),w=m.toLowerCase();
      if(SUP_VY_KEEP.test(w))return m;
      if(e==='йте')return base+'й';if(e==='йтесь')return base+'йся';
      if(e==='ьте')return base+'ь';if(e==='ьтесь')return base+'ься';
      if(!SUP_VY_ITE.test(w))return m; // «в защите», «на орбите» — не трогаем
      return e==='ите'?base+'и':base+'ись';
    });
  }
  return s;
}

// Похожесть ответов по словам (Жаккар): маленькая модель любит повторять свой прошлый ответ
function supWords(t){return new Set(supNorm(t).replace(/[^а-яa-z0-9 ]/g,' ').split(' ').filter(w=>w.length>2));}
function supSimilar(a,b){
  const A=supWords(a),B=supWords(b);if(!A.size||!B.size)return 0;
  let n=0;A.forEach(w=>{if(B.has(w))n++;});
  return n/(A.size+B.size-n);
}
function supRepeats(text,history){
  return(history||[]).filter(m=>m.r==='a'&&m.t).slice(-4).some(m=>supSimilar(text,m.t)>0.5);
}

// Запасной ответ: пример под ситуацию, который ещё не звучал в этом разговоре
function supFallback(d,text,history,sex){
  const id=(d.intents||[]).find(x=>SUP_EXAMPLES[x])||'default';
  const said=(history||[]).filter(m=>m.r==='a').map(m=>m.t);
  const pool=[...SUP_EXAMPLES[id],...SUP_EXAMPLES.default].map(x=>supG(x[1],sex)).filter(a=>!said.some(s=>supSimilar(a,s)>0.5));
  return pool.length?pool[supHash(text)%pool.length]:'Я здесь и слушаю. Расскажи чуть подробнее — что ты чувствуешь прямо сейчас?';
}

// Ответ никуда не годится — лучше перегенерировать
function supIsBad(text){
  const t=String(text||'').trim();
  if(t.length<8)return true;
  const lat=(t.match(/[a-z]/gi)||[]).length,cyr=(t.match(/[а-яё]/gi)||[]).length;
  if(cyr<lat||lat>12)return true;
  if(/(^|[^а-яё])(вы|вам|вас|ваш\w*|вами)([^а-яё]|$)/i.test(t))return true;          // перешёл на «вы»
  if(/как лучше ответить|подсказк|сейчас: человек/i.test(t))return true;              // пересказал инструкцию
  return false;
}

